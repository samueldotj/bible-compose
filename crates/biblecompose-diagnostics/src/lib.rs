//! Typed errors and warnings shared by every BibleCompose stage.
//!
//! One `Diagnostic` type, produced by eight stages, rendered by one panel.
//! See ARCHITECTURE §10.
//!
//! Two rules are enforced here rather than by convention:
//!
//! * **A code cannot disagree with its stage.** Codes are generated from the
//!   stage that declares them ([`codes!`]), so `Stage::Config` cannot carry a
//!   `USFM-` code. DIA-001.
//! * **Diagnostics quote at most one elided source line.** NFR-010 asks logs
//!   not to record Scripture unnecessarily, which is easy at the start and
//!   impossible once a log format is relied upon. [`Quote::elided`] is the
//!   only way to attach source text.

use std::fmt;

use camino::Utf8PathBuf;
use serde::{Deserialize, Serialize};

/// Where a diagnostic came from. The prefix is the first half of every code
/// that stage can produce, which is what makes DIA-004's filtering a field
/// comparison rather than a string match.
#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord, Hash, Serialize, Deserialize)]
pub enum Stage {
    Discovery,
    Usfm,
    Config,
    Style,
    Asset,
    Font,
    Backend,
    Output,
}

impl Stage {
    pub const fn prefix(self) -> &'static str {
        match self {
            Stage::Discovery => "PRJ",
            Stage::Usfm => "USFM",
            Stage::Config => "CFG",
            Stage::Style => "STY",
            Stage::Asset => "ASSET",
            Stage::Font => "FONT",
            Stage::Backend => "SILE",
            Stage::Output => "OUT",
        }
    }

    pub const fn all() -> &'static [Stage] {
        use Stage::*;
        &[Discovery, Usfm, Config, Style, Asset, Font, Backend, Output]
    }
}

impl fmt::Display for Stage {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        f.write_str(self.prefix())
    }
}

#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord, Hash, Serialize, Deserialize)]
pub enum Severity {
    /// Blocks the build. Validation runs to completion first, so a blocked
    /// build reports every one of these at once (DIA-002).
    Error,
    /// The build proceeds (DIA-003).
    Warning,
    Info,
}

impl Severity {
    pub const fn blocks(self) -> bool {
        matches!(self, Severity::Error)
    }
}

impl fmt::Display for Severity {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        f.write_str(match self {
            Severity::Error => "error",
            Severity::Warning => "warning",
            Severity::Info => "info",
        })
    }
}

/// A stable machine-readable code (DIA-001).
///
/// There is no public constructor taking an arbitrary string: every value is
/// generated by [`codes!`] from the stage that owns it, so the `id` and the
/// `stage` cannot drift apart.
#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord, Hash)]
pub struct Code {
    stage: Stage,
    id: &'static str,
}

/// Serialized as the bare code string — `"CFG-002"`, not a struct. The stage
/// is recoverable from the prefix, so writing both would be a way for the two
/// to disagree on the wire.
impl Serialize for Code {
    fn serialize<S: serde::Serializer>(&self, s: S) -> Result<S::Ok, S::Error> {
        s.serialize_str(self.id)
    }
}

/// Deserialization is a lookup, not a construction: an unknown code is an
/// error rather than a `Code` nothing can interpret.
impl<'de> Deserialize<'de> for Code {
    fn deserialize<D: serde::Deserializer<'de>>(d: D) -> Result<Code, D::Error> {
        let s = String::deserialize(d)?;
        code::ALL
            .iter()
            .find(|c| c.id == s)
            .copied()
            .ok_or_else(|| serde::de::Error::custom(format!("unknown diagnostic code {s:?}")))
    }
}

impl Code {
    pub const fn stage(self) -> Stage {
        self.stage
    }

    pub const fn as_str(self) -> &'static str {
        self.id
    }
}

impl fmt::Display for Code {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        f.write_str(self.id)
    }
}

/// Compile-time string equality, so [`codes!`] can assert that a group's
/// prefix literal really is the one its stage declares.
#[doc(hidden)]
pub const fn __str_eq(a: &str, b: &str) -> bool {
    let (a, b) = (a.as_bytes(), b.as_bytes());
    if a.len() != b.len() {
        return false;
    }
    let mut i = 0;
    while i < a.len() {
        if a[i] != b[i] {
            return false;
        }
        i += 1;
    }
    true
}

/// Declares codes grouped by the stage that owns them.
///
/// The prefix literal appears once per group and is **checked against
/// [`Stage::prefix`] at compile time**, so `Config "USFM" { … }` does not
/// build. `concat!` needs a literal, which is why the prefix is written rather
/// than derived — the const assertion is what closes the gap.
#[macro_export]
macro_rules! codes {
    ($( $stage:ident $prefix:literal { $( $name:ident = $id:literal ),* $(,)? } )*) => {
        $(
            const _: () = assert!(
                $crate::__str_eq($crate::Stage::$stage.prefix(), $prefix),
                concat!("diagnostic group ", stringify!($stage), " declares the wrong prefix"),
            );

            $(
                pub const $name: $crate::Code = $crate::Code::__declare(
                    $crate::Stage::$stage,
                    ::std::concat!($prefix, "-", $id),
                );
            )*
        )*

        /// Every code declared in this module, for the invariant test and for
        /// documentation generation.
        pub const ALL: &[$crate::Code] = &[ $( $( $name ),* ),* ];
    };
}

impl Code {
    /// Not for direct use — [`codes!`] is the supported constructor. Public
    /// only because the macro expands in the caller's crate.
    #[doc(hidden)]
    pub const fn __declare(stage: Stage, id: &'static str) -> Code {
        Code { stage, id }
    }
}

/// A position in a project file.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct SourceLoc {
    pub path: Utf8PathBuf,
    pub line: Option<u32>,
    pub column: Option<u32>,
}

impl SourceLoc {
    pub fn file(path: impl Into<Utf8PathBuf>) -> Self {
        SourceLoc {
            path: path.into(),
            line: None,
            column: None,
        }
    }

    pub fn at(path: impl Into<Utf8PathBuf>, line: u32, column: u32) -> Self {
        SourceLoc {
            path: path.into(),
            line: Some(line),
            column: Some(column),
        }
    }
}

impl fmt::Display for SourceLoc {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        write!(f, "{}", self.path)?;
        if let Some(line) = self.line {
            write!(f, ":{line}")?;
            if let Some(column) = self.column {
                write!(f, ":{column}")?;
            }
        }
        Ok(())
    }
}

/// A Scripture reference, for diagnostics that can name one.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct ScriptureRef {
    pub book: String,
    pub chapter: u16,
    pub verse: Option<u16>,
}

impl fmt::Display for ScriptureRef {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        write!(f, "{} {}", self.book, self.chapter)?;
        if let Some(v) = self.verse {
            write!(f, ":{v}")?;
        }
        Ok(())
    }
}

/// At most one line of source text, elided to a bounded width.
///
/// NFR-010: logs should carry only the context needed to identify a problem.
/// Constructing this any other way is not possible, so a full verse cannot
/// reach the log by accident.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct Quote(String);

impl Quote {
    pub const MAX: usize = 60;

    /// Takes one line, trims it, and elides the middle if it is too long.
    pub fn elided(line: &str) -> Quote {
        let line = line.lines().next().unwrap_or("").trim();
        let chars: Vec<char> = line.chars().collect();
        if chars.len() <= Self::MAX {
            return Quote(line.to_owned());
        }
        let keep = (Self::MAX - 1) / 2;
        let head: String = chars[..keep].iter().collect();
        let tail: String = chars[chars.len() - keep..].iter().collect();
        Quote(format!("{head}…{tail}"))
    }

    pub fn as_str(&self) -> &str {
        &self.0
    }
}

impl fmt::Display for Quote {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        f.write_str(&self.0)
    }
}

#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct Diagnostic {
    pub severity: Severity,
    pub code: Code,
    pub message: String,
    pub location: Option<SourceLoc>,
    pub reference: Option<ScriptureRef>,
    pub help: Option<String>,
    pub quote: Option<Quote>,
    /// Raw backend text, collapsed by default in any UI (DIA-005).
    pub detail: Option<String>,
}

impl Diagnostic {
    pub fn new(severity: Severity, code: Code, message: impl Into<String>) -> Self {
        Diagnostic {
            severity,
            code,
            message: message.into(),
            location: None,
            reference: None,
            help: None,
            quote: None,
            detail: None,
        }
    }

    pub fn error(code: Code, message: impl Into<String>) -> Self {
        Self::new(Severity::Error, code, message)
    }

    pub fn warning(code: Code, message: impl Into<String>) -> Self {
        Self::new(Severity::Warning, code, message)
    }

    pub fn info(code: Code, message: impl Into<String>) -> Self {
        Self::new(Severity::Info, code, message)
    }

    pub fn at(mut self, loc: SourceLoc) -> Self {
        self.location = Some(loc);
        self
    }

    pub fn about(mut self, reference: ScriptureRef) -> Self {
        self.reference = Some(reference);
        self
    }

    pub fn help(mut self, help: impl Into<String>) -> Self {
        self.help = Some(help.into());
        self
    }

    pub fn quoting(mut self, line: &str) -> Self {
        self.quote = Some(Quote::elided(line));
        self
    }

    pub fn detail(mut self, detail: impl Into<String>) -> Self {
        self.detail = Some(detail.into());
        self
    }

    pub fn stage(&self) -> Stage {
        self.code.stage()
    }
}

impl fmt::Display for Diagnostic {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        write!(f, "{}[{}]", self.severity, self.code)?;
        if let Some(loc) = &self.location {
            write!(f, " {loc}")?;
        }
        if let Some(r) = &self.reference {
            write!(f, " ({r})")?;
        }
        write!(f, ": {}", self.message)
    }
}

/// A collection with the one question the build orchestrator asks of it.
#[derive(Debug, Clone, Default, Serialize, Deserialize)]
pub struct Diagnostics {
    items: Vec<Diagnostic>,
}

impl Diagnostics {
    pub fn new() -> Self {
        Self::default()
    }

    pub fn push(&mut self, d: Diagnostic) {
        self.items.push(d);
    }

    pub fn extend(&mut self, other: impl IntoIterator<Item = Diagnostic>) {
        self.items.extend(other);
    }

    pub fn iter(&self) -> impl Iterator<Item = &Diagnostic> {
        self.items.iter()
    }

    pub fn len(&self) -> usize {
        self.items.len()
    }

    pub fn is_empty(&self) -> bool {
        self.items.is_empty()
    }

    /// DIA-002: the build is blocked if any diagnostic blocks it, and the
    /// caller reports all of them before the backend is invoked.
    pub fn blocking(&self) -> impl Iterator<Item = &Diagnostic> {
        self.items.iter().filter(|d| d.severity.blocks())
    }

    pub fn has_blocking(&self) -> bool {
        self.items.iter().any(|d| d.severity.blocks())
    }

    pub fn by_stage(&self, stage: Stage) -> impl Iterator<Item = &Diagnostic> {
        self.items.iter().filter(move |d| d.stage() == stage)
    }
}

impl IntoIterator for Diagnostics {
    type Item = Diagnostic;
    type IntoIter = std::vec::IntoIter<Diagnostic>;
    fn into_iter(self) -> Self::IntoIter {
        self.items.into_iter()
    }
}

