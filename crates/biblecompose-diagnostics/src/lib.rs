#[cfg(test)]
mod tests {
    use super::*;

    /// DIA-001. The macro makes a mismatch impossible to write; this asserts
    /// the invariant over every declared code, so a hand-rolled `__declare`
    /// bypassing the macro is caught too.
    #[test]
    fn every_code_carries_its_own_stage_prefix() {
        assert!(!code::ALL.is_empty());
        for c in code::ALL {
            let expected = format!("{}-", c.stage().prefix());
            assert!(
                c.as_str().starts_with(&expected),
                "code {} belongs to stage {} and must start with {expected}",
                c.as_str(),
                c.stage()
            );
        }
    }

    #[test]
    fn codes_are_unique() {
        let mut seen: Vec<&str> = code::ALL.iter().map(|c| c.as_str()).collect();
        seen.sort_unstable();
        let before = seen.len();
        seen.dedup();
        assert_eq!(before, seen.len(), "duplicate diagnostic code");
    }

    #[test]
    fn every_stage_has_a_distinct_prefix() {
        let mut prefixes: Vec<&str> = Stage::all().iter().map(|s| s.prefix()).collect();
        prefixes.sort_unstable();
        let before = prefixes.len();
        prefixes.dedup();
        assert_eq!(before, prefixes.len(), "two stages share a prefix");
    }

    #[test]
    fn blocking_is_only_errors() {
        let mut d = Diagnostics::new();
        d.push(Diagnostic::warning(code::UNKNOWN_KEY, "typo"));
        assert!(!d.has_blocking());
        d.push(Diagnostic::error(code::INVALID_TOML, "bad"));
        assert!(d.has_blocking());
        assert_eq!(d.blocking().count(), 1);
    }

    #[test]
    fn quote_elides_long_lines_and_keeps_short_ones() {
        let short = Quote::elided("  In the beginning  ");
        assert_eq!(short.as_str(), "In the beginning");

        let long = "x".repeat(500);
        let q = Quote::elided(&long);
        assert!(q.as_str().chars().count() <= Quote::MAX);
        assert!(q.as_str().contains('…'));
    }

    #[test]
    fn quote_takes_only_the_first_line() {
        let q = Quote::elided("first line\nsecond line\nthird");
        assert_eq!(q.as_str(), "first line");
    }

    #[test]
    fn display_is_readable() {
        let d = Diagnostic::error(code::DUPLICATE_BOOK_ID, "two files declare \\id MAT")
            .at(SourceLoc::at("books/MAT.usfm", 1, 1));
        assert_eq!(
            d.to_string(),
            "error[PRJ-001] books/MAT.usfm:1:1: two files declare \\id MAT"
        );
    }
}
